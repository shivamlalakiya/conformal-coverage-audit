# ---------------------------------------------------------------------------
# (A) clustered sign-flip permutation test
# ---------------------------------------------------------------------------
def clustered_permutation(per_series, reps=PERMS, seed=SEED):
    """Two-sided p for mean(delta) = 0, flipping SIGNS within clusters.

    `per_series` is one mean paired difference per series. Under the null of no
    effect a unit's difference is as likely to be negative as positive, so the null
    distribution is generated by flipping the sign of whole clusters -- never of
    individual points inside a cluster, which would treat dependent origins as
    independent and shrink the p-value.
    """
    x = np.asarray([v for v in per_series if not math.isnan(v)], float)
    if x.size == 0:
        return float("nan"), 0
    obs = abs(float(x.mean()))
    rng = np.random.default_rng(seed)
    signs = rng.choice((-1.0, 1.0), size=(reps, x.size))
    null = np.abs((signs * x).mean(axis=1))
    # +1 in numerator and denominator: the observed assignment is one of the
    # attainable ones, so a p of exactly zero is not attainable and should not be
    # reported
    p = (1.0 + float(np.sum(null >= obs - 1e-15))) / (reps + 1.0)
    return p, x.size


def holm(pvals):
    """Holm-Bonferroni adjusted p-values, in the input order.

    Holm rather than plain Bonferroni because it is uniformly at least as powerful
    and no less valid, and because reporting the weakest available correction would
    make "nothing moved" a claim about the correction rather than about the data.
    """
    order = sorted(range(len(pvals)), key=lambda i: pvals[i])
    m, out, running = len(pvals), [0.0] * len(pvals), 0.0
    for rank, i in enumerate(order):
        adj = min(1.0, (m - rank) * pvals[i])
        running = max(running, adj)
        out[i] = running
    return out


