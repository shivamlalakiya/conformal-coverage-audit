# (B) the index arithmetic, re-implemented in R
# ---------------------------------------------------------------------------
R_CODE = r'''
required_rank <- function(n, cov) {
  k <- ceiling((n + 1) * cov)
  if (k <= n) k else NA_integer_
}
required_span <- function(n, cov) {
  k <- ceiling((n + 1) * cov); m <- n + 1 - k; a <- m %/% 2
  c(a, a + k, k)
}
h_linear  <- function(n, q) 1 + q * (n - 1)
h_weibull <- function(n, q) q * (n + 1)
h_invcdf  <- function(n, q) ceiling(q * n)
h_higher  <- function(n, q) ceiling(q * (n - 1)) + 1
delivers  <- function(hf, n, cov) floor(hf(n, cov)) >= ceiling((n + 1) * cov)

out <- c()
for (n in c(2, 3, 7, 9, 10, 19, 20, 29, 47, 50, 99, 100, 200, 501)) {
  for (cov in c(0.90, 0.95, 2/3, 5/7)) {
    rr <- required_rank(n, cov)
    sp <- required_span(n, cov)
    out <- c(out, sprintf("%d %.10f %s %d %d %d %.10f %.10f %d %d %d %d %d %d",
      n, cov, ifelse(is.na(rr), "NA", as.character(rr)),
      sp[1], sp[2], sp[3],
      h_linear(n, cov), h_weibull(n, cov), h_invcdf(n, cov), h_higher(n, cov),
      as.integer(delivers(h_linear, n, cov)),
      as.integer(delivers(h_weibull, n, cov)),
      as.integer(delivers(h_invcdf, n, cov)),
      as.integer(delivers(h_higher, n, cov))))
  }
}
cat(out, sep = "\n")
cat("\n")
'''


def py_reference(n, cov):
    """The Python side of the cross-check, from the shipped probe module."""
    rr = SK.required_rank(n, cov)
    a, b, k = SK.required_span(n, cov)
    c = F(cov).limit_denominator(10 ** 6)

    def dels(h):
        return int(math.floor(h) >= math.ceil(F(n + 1) * c))
    h_lin = 1 + c * (n - 1)
    h_wei = c * (n + 1)
    h_inv = math.ceil(c * n)
    h_hig = math.ceil(c * (n - 1)) + 1
    return {"rr": rr, "a": a, "b": b, "k": k,
            "h_lin": float(h_lin), "h_wei": float(h_wei),
            "h_inv": h_inv, "h_hig": h_hig,
            "d_lin": dels(h_lin), "d_wei": dels(h_wei),
            "d_inv": dels(h_inv), "d_hig": dels(h_hig)}


def run_r():
    if not shutil.which("Rscript"):
        return None, "Rscript not on PATH"
    with tempfile.NamedTemporaryFile("w", suffix=".R", delete=False) as fh:
        fh.write(R_CODE)
        path = fh.name
    try:
        p = subprocess.run(["Rscript", "--vanilla", path],
                           capture_output=True, text=True, timeout=300)
    finally:
        os.unlink(path)
    if p.returncode != 0:
        return None, (p.stderr or "").strip()[:160]
    rows = {}
    for ln in p.stdout.strip().splitlines():
        f = ln.split()
        if len(f) != 14:
            continue
        n, cov = int(f[0]), float(f[1])
        rows[(n, round(cov, 10))] = {
            "rr": None if f[2] == "NA" else int(f[2]),
            "a": int(f[3]), "b": int(f[4]), "k": int(f[5]),
            "h_lin": float(f[6]), "h_wei": float(f[7]),
            "h_inv": int(f[8]), "h_hig": int(f[9]),
            "d_lin": int(f[10]), "d_wei": int(f[11]),
            "d_inv": int(f[12]), "d_hig": int(f[13]),
        }
    return rows, None


# ---------------------------------------------------------------------------
# (C) absolute error against exceedance-rate error
# ---------------------------------------------------------------------------
def exceedance_factor(n, level):
    """What a one-rank miss costs, absolutely and as a rate.

    A helper landing one rank short of k* delivers (k*-1)/(n+1) instead of
    k*/(n+1). The absolute coverage miss is 1/(n+1) whatever the level. The
    exceedance rate a risk report states is 1 - coverage, so the RATIO of the
    delivered rate to the requested one is what a reader of that report sees.
    """
    c = F(level).limit_denominator(10 ** 6)
    k = math.ceil(F(n + 1) * c)
    if k > n or k < 2:
        return None
    got = F(k - 1, n + 1)
    want = F(k, n + 1)
    exc_got, exc_want = 1 - got, 1 - want
    return {"abs": float(want - got), "rate_got": float(exc_got),
            "rate_want": float(exc_want),
            "factor": float(exc_got / exc_want) if exc_want > 0 else float("inf")}


def self_check():
    # (A) the test must reject a planted effect and not reject noise
    rng = np.random.default_rng(3)
    p_null, _ = clustered_permutation(rng.normal(0, 1, 60), reps=4000, seed=1)
    assert p_null > 0.05, p_null
    p_eff, _ = clustered_permutation(rng.normal(1.2, 1, 60), reps=4000, seed=1)
    assert p_eff < 0.01, p_eff
    # a p of exactly zero must be unreachable
    assert clustered_permutation(np.ones(40), reps=999, seed=1)[0] > 0
    # (A) Holm must be monotone, bounded by 1, and no smaller than the raw p
    raw = [0.001, 0.02, 0.2, 0.9]
    adj = holm(raw)
    assert all(a >= r - 1e-12 for a, r in zip(adj, raw)), (raw, adj)
    assert all(a <= 1 for a in adj)
    assert adj == sorted(adj), adj
    # (C) the absolute miss is 1/(n+1) whatever the level, and the rate factor
    # grows as the level tightens -- which is the whole point of section (C)
    a90 = exceedance_factor(200, 0.90)
    a99 = exceedance_factor(200, 0.99)
    assert abs(a90["abs"] - a99["abs"]) < 1e-12, (a90, a99)
    assert a99["factor"] > a90["factor"] > 1.0, (a90, a99)


self_check()


