"""Three loose ends: multiplicity, an independent re-implementation, and cost.

(A) MULTIPLICITY, WITH THE CORRECTION APPLIED RATHER THAN DISCLAIMED
The limitations section says roughly a hundred cells are reported with no
multiplicity adjustment, and argues one would change nothing because the central
claims are exact arithmetic rather than tests. That argument is correct and it is
still weaker than doing the correction. So: a clustered permutation test per
forecasting arm, with a family-wise correction across arms, on the paired
differences. If nothing moves, the sentence becomes "we corrected and nothing
moved", which is strictly stronger than "we did not correct".

The permutation respects the design. A paired difference per unit is exchangeable
under the null of no effect ONLY up to its sign, so the null distribution is
generated by flipping signs within a unit, and the unit is a SERIES rather than a
test point wherever a series contributes several -- the same clustering the
robustness table uses, for the same reason.

(B) AN INDEPENDENT RE-IMPLEMENTATION OF THE INDEX ARITHMETIC
The standing failure mode here is a parser or a closed form agreeing with itself:
two of the ten gates re-derive through the layer they check, and the fixture audit
is done by the same person who wrote the builder. R and Julia are already driven by
the cross-language probe, so the index arithmetic -- required rank, required span,
the virtual index, the delivering set -- is re-implemented in R and cross-checked
against the Python. A disagreement is a finding; agreement is the independence the
fixture audit cannot supply on its own.

(C) WHY A SMALL COVERAGE ERROR IS NOT A SMALL ERROR
The generalisation section makes this point for value-at-risk: in ABSOLUTE terms a
one-rank miss is O(1/n), but the quantity a risk report states is the exceedance
RATE, and there the same error is a multiplicative factor. Stated once for one
setting it reads as a rhetorical flourish. Computed across the levels a
practitioner actually requests, it is a table: the tighter the level, the larger the
factor, because 1/(n+1) is a fixed slice of an alpha that is shrinking.

    python probes/multiplicity_and_reimpl.py
"""

